"""The paper build: figures land where they are cited, and gaps are visible.

The build exists to rerun every time a result lands, so the failure that
matters is a silent one: a figure cited and not shown, or shown twice, or a
figure built and never referred to.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
import build_paper as B  # noqa: E402


def _png(tmp_path, name):
    p = tmp_path / name
    # a one pixel PNG, enough to be embedded
    p.write_bytes(bytes.fromhex(
        "89504e470d0a1a0a0000000d4948445200000001000000010806000000"
        "1f15c4890000000a49444154789c6300010000050001od".replace("od", "0d")
        + "0a2db40000000049454e44ae426082"))
    return p


def test_figure_numbers_come_from_the_filenames(tmp_path) -> None:
    _png(tmp_path, "f3_patching.png")
    _png(tmp_path, "f10_attractor.png")
    got = B.find_figures(tmp_path)
    assert sorted(got) == [3, 10], "10 must not be read as 1"


def test_a_figure_is_placed_after_the_paragraph_that_cites_it(tmp_path) -> None:
    figs = {9: _png(tmp_path, "f9_binding.png")}
    md = "intro para\n\ncites **Figure 9** here\n\nafter para"
    out, placed, missing = B.insert_figures(md, figs)
    assert placed == [9] and missing == []
    before, after = out.split("<figure>")[0], out.split("</figure>")[1]
    assert "cites" in before, "the figure must follow its citation"
    assert "after para" in after


def test_a_figure_cited_twice_appears_once(tmp_path) -> None:
    """A figure referred to in three sections should not be embedded three
    times, which would triple the file size and read as three figures."""
    figs = {9: _png(tmp_path, "f9_binding.png")}
    md = "**Figure 9** first\n\nmiddle\n\nand **Figure 9** again"
    out, placed, _ = B.insert_figures(md, figs)
    assert placed == [9]
    assert out.count("<figure>") == 1


def test_a_cited_figure_that_is_not_built_becomes_visible(tmp_path) -> None:
    """Silently dropping a figure the text refers to is worse than saying it
    is not built. A reader hits a dangling reference either way; only one of
    them tells them why."""
    out, placed, missing = B.insert_figures("see **Figure 7** here", {})
    assert placed == [] and missing == [7]
    assert 'class="missing"' in out
    # The reader's number, and the file it should have come from.
    assert "Figure 1 (file f7)" in out


def test_figures_are_numbered_in_order_of_first_citation(tmp_path) -> None:
    """The draft cites by file number. A reader sees 1, 2, 3 in the order the
    text first mentions them, and a later mention keeps the first number. The
    9 October draft printed its figures as 1, 9, 8, 2, 6, 3, 10, 4, 5."""
    figs = {9: _png(tmp_path, "f9_binding.png"), 1: _png(tmp_path, "f1_tasks.png"),
            8: _png(tmp_path, "f8_absent.png")}
    md = "see **Figure 9**\n\nthen **Figure 1** and **Figure 8**\n\nback to **Figure 9**"
    out, placed, _ = B.insert_figures(md, figs)
    assert B.display_order(md) == {9: 1, 1: 2, 8: 3}
    assert placed == [9, 1, 8]
    assert "see **Figure 1**" in out and "then **Figure 2** and **Figure 3**" in out
    assert "back to **Figure 1**" in out
    assert "**Figure 9**" not in out
    caps = [line for line in out.split("<figcaption>")[1:]]
    assert [c[:len("<b>Figure 1.</b>")] for c in caps] == ["<b>Figure 1.</b>", "<b>Figure 2.</b>", "<b>Figure 3.</b>"]


def test_two_figures_first_cited_together_land_in_reading_order(tmp_path) -> None:
    figs = {4: _png(tmp_path, "f4_coda.png"), 2: _png(tmp_path, "f2_curves.png")}
    out, placed, _ = B.insert_figures("**Figure 4** and **Figure 2**", figs)
    assert placed == [4, 2], "Figure 1 must come before Figure 2 on the page"


def test_a_caption_comes_from_the_draft_and_a_missing_one_shows(tmp_path) -> None:
    figs = {3: _png(tmp_path, "f3_patching.png"), 6: _png(tmp_path, "f6_halting.png")}
    md = ("**Figure 3** here\n\n<!-- figure 3: Patching effect\n   by family. -->\n\n"
          "and **Figure 6** there")
    out, _, _ = B.insert_figures(md, figs)
    assert "<b>Figure 1.</b> Patching effect by family.</figcaption>" in out
    assert "No caption written for f6" in out


def test_no_caption_says_generated_by(tmp_path) -> None:
    """Every caption used to read "Generated by f9_binding.png, which reads a
    stored metrics file and computes nothing": a file name, not a caption, and
    wrong for the benchmark figure, which shows generator samples."""
    draft = tmp_path / "d.md"
    draft.write_text("# T\n\nsee **Figure 2** now\n\n<!-- figure 2: Curves. -->", encoding="utf-8")
    figdir = tmp_path / "figs"
    figdir.mkdir()
    _png(figdir, "f2_curves.png")
    out = tmp_path / "out.html"
    B.build(draft, figdir, out)
    html = out.read_text(encoding="utf-8")
    assert "Generated by" not in html and "<b>Figure 1.</b> Curves." in html


def test_two_figures_in_one_paragraph_both_land(tmp_path) -> None:
    figs = {4: _png(tmp_path, "f4_coda.png"), 5: _png(tmp_path, "f5_geometry.png")}
    out, placed, _ = B.insert_figures("**Figure 4** and **Figure 5**", figs)
    assert placed == [4, 5]
    assert out.count("<figure>") == 2


def test_the_build_reports_figures_built_but_never_cited(tmp_path, capsys) -> None:
    """A figure nobody refers to is either a missing citation or a figure
    that does not belong, and both are worth saying out loud."""
    draft = tmp_path / "d.md"
    draft.write_text("# T\n\nno citations here", encoding="utf-8")
    figdir = tmp_path / "figs"
    figdir.mkdir()
    _png(figdir, "f2_curves.png")
    B.build(draft, figdir, tmp_path / "out.html")
    assert "never cited" in capsys.readouterr().out


def test_the_output_is_self_contained(tmp_path) -> None:
    """One file that survives being emailed. An external src would break the
    moment it left this machine."""
    draft = tmp_path / "d.md"
    draft.write_text("# T\n\nsee **Figure 2** now", encoding="utf-8")
    figdir = tmp_path / "figs"
    figdir.mkdir()
    _png(figdir, "f2_curves.png")
    out = tmp_path / "out.html"
    B.build(draft, figdir, out)
    html = out.read_text(encoding="utf-8")
    assert "data:image/png;base64," in html
    assert 'src="f2' not in html and "src='f2" not in html


def test_the_figure_directory_is_found_inside_the_repository(tmp_path) -> None:
    """The cluster keeps figures inside the checkout, the Windows machine
    beside it. The default was the local layout only, so the build died on
    the cluster with "no figure directory" while nine figures sat in the
    checkout, on the one machine that has the runs."""
    root = tmp_path / "repo"
    (root / "figures").mkdir(parents=True)
    assert B.default_figures(root) == root / "figures"


def test_the_figure_directory_is_found_beside_the_repository(tmp_path) -> None:
    """The other layout still has to work, or fixing the cluster breaks the
    machine the script was written on."""
    root = tmp_path / "repo"
    root.mkdir()
    (tmp_path / "figures").mkdir()
    assert B.default_figures(root) == tmp_path / "figures"


def test_inside_the_repository_wins_when_both_exist(tmp_path) -> None:
    """Two directories both named figures is exactly when a silent wrong
    choice costs a reader a stale picture, so the tie is broken on purpose
    and not by whichever branch happened to run first. Inside wins: that
    copy sits next to the metrics the figures were drawn from."""
    root = tmp_path / "repo"
    (root / "figures").mkdir(parents=True)
    (tmp_path / "figures").mkdir()
    assert B.default_figures(root) == root / "figures"
