"""Write the configs for D-066 to D-069, the revision experiments of 2026-10-11.

    python scripts/make_revision_configs.py

Each config is its base config with exactly the changes its registration
names, so tests/test_revision_configs.py can check the difference key by key.
Run names start c1_ to c4_ so that no existing module, all of which select
runs by name, can count them into a registration they do not belong to, and
no arm name ends in "s", because the shared stem() strips a trailing "s"
along with the seed.
"""

from __future__ import annotations

from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "configs" / "rev"

EARLY_STOP = {"early_stop_tau": 0.95, "early_stop_window": 20000}

BASES = {
    "pos": ROOT / "configs" / "m3" / "famA_d2_d4only.yaml",
    "app": ROOT / "configs" / "m3" / "famA_d2_d4colour.yaml",
    "e2a_cue": ROOT / "configs" / "why" / "e2a_cue.yaml",
    "e2b_decoy": ROOT / "configs" / "why" / "e2b_decoy.yaml",
    "curr": ROOT / "configs" / "m3" / "famA_d2_d4colour_curriculum_confirm_s10.yaml",
    "currctrl": ROOT / "configs" / "m3" / "famA_d2_d4colour_curriculum_ctrl_confirm_s10.yaml",
    "s3donor": ROOT / "configs" / "m3" / "famA_d2_d4colour_curriculum_s3donor_confirm_s10.yaml",
}

#: D-066's grid. Names are filesystem safe and never end in "s".
LRS = {"lr1e4": 1e-4, "lr3e4": 3e-4, "lr1e3": 1e-3}
WDS = {"wd005": 0.05, "wd05": 0.5}

#: D-069's donors, one per recipient seed, the depth 1 configs every
#: existing curriculum donor used.
DONOR_STEM = {"curr": "famA_d1_d4colour", "currctrl": "famA_d1_d4only",
              "s3donor": "famA_d1_s3only"}
C4_SEEDS = range(15, 25)


def base(name: str) -> dict:
    return yaml.safe_load(BASES[name].read_text(encoding="utf-8"))


def changes() -> dict[str, tuple[str, dict, str]]:
    """config name -> (base name, the registered changes, why)."""
    out: dict[str, tuple[str, dict, str]] = {}
    for sub in ("pos", "app"):
        for lname, lr in LRS.items():
            for wname, wd in WDS.items():
                out[f"c1_{sub}_{lname}_{wname}"] = (
                    sub, {"lr": lr, "weight_decay": wd, **EARLY_STOP, "experiment": "C1"},
                    f"D-066 grid cell lr {lr}, weight decay {wd}")
    for sub in ("pos", "app"):
        out[f"c2_{sub}_x2"] = (sub, {"pixel_scale": 2, **EARLY_STOP, "experiment": "C2"},
                               "D-067 glyphs spanning 2x2 patches")
    for arm in ("e2a_cue", "e2b_decoy"):
        out[f"c3_{arm}"] = (arm, {**EARLY_STOP, "experiment": "C3"},
                            "D-068 more seeds of the D-062 rendering")
    for arm, donor in DONOR_STEM.items():
        for s in C4_SEEDS:
            out[f"c4_{arm}_s{s}"] = (
                arm, {"init_from": f"{donor}_s{s}", "confirmation": True, **EARLY_STOP,
                      "experiment": "C4"},
                f"D-069 held-out recipient from the donor of its own seed, {donor}_s{s}")
    return out


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, (b, delta, why) in changes().items():
        cfg = base(b)
        cfg.update(delta)
        head = (f"# {name}: {why}.\n"
                f"# Generated by scripts/make_revision_configs.py from {BASES[b].relative_to(ROOT).as_posix()},\n"
                f"# changing only: {', '.join(sorted(delta))}. Checked by tests/test_revision_configs.py.\n")
        (OUT / f"{name}.yaml").write_text(head + yaml.safe_dump(cfg, sort_keys=True), encoding="utf-8")
    print(f"wrote {len(changes())} configs to {OUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
